// ---- SMB/Samba server management ----
//
// These endpoints manage the Samba *server* running on the CasaNova host:
// creating/editing shared folders, toggling smbd, and browsing the LAN
// for other SMB servers. They are independent of the legacy samba.go
// which handles client-side mount connections.

const smbConfigPath = "/var/lib/casanova/smb_shares.json"
const smbConfPath = "/etc/samba/smb.conf"

var smbMu sync.Mutex

// ---- Data types ----

type SmbShare struct {
	Name       string   `json:"name"`
	Path       string   `json:"path"`
	ReadOnly   bool     `json:"read_only"`
	GuestOk    bool     `json:"guest_ok"`
	Comment    string   `json:"comment"`
	ValidUsers []string `json:"valid_users,omitempty"`
}

type SmbConfig struct {
	Enabled   bool       `json:"enabled"`
	Workgroup string     `json:"workgroup"`
	Shares    []SmbShare `json:"shares"`
}

type SmbStatusResponse struct {
	Installed bool       `json:"installed"`
	Running   bool       `json:"running"`
	Workgroup string     `json:"workgroup"`
	Shares    []SmbShare `json:"shares"`
}

type SmbBrowseEntry struct {
	Host   string   `json:"host"`
	Shares []string `json:"shares,omitempty"`
}

// ---- Persistence helpers ----

func loadSmbConfig() (SmbConfig, error) {
	cfg := SmbConfig{
		Enabled:   false,
		Workgroup: "WORKGROUP",
		Shares:    []SmbShare{},
	}
	data, err := os.ReadFile(smbConfigPath)
	if err != nil {
		if os.IsNotExist(err) {
			return cfg, nil
		}
		return cfg, err
	}
	if err := json.Unmarshal(data, &cfg); err != nil {
		return cfg, err
	}
	if cfg.Shares == nil {
		cfg.Shares = []SmbShare{}
	}
	return cfg, nil
}

func saveSmbConfig(cfg SmbConfig) error {
	dir := filepath.Dir(smbConfigPath)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	data, err := json.MarshalIndent(cfg, "", "  ")
	if err != nil {
		return err
	}
	// Wave 35-X: atomic write — power loss mid-write loses all
	// share definitions.
	return commonfile.WriteFileAtomic(smbConfigPath, data, 0o644)
}

// ---- smb.conf generation ----

// sanitizeSmbField strips characters that could inject new Samba directives
// (newlines to break out of a value, brackets to start a new section).
func sanitizeSmbField(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "\r", " ")
	s = strings.ReplaceAll(s, "[", "")
	s = strings.ReplaceAll(s, "]", "")
	return strings.TrimSpace(s)
}

func generateSmbConf(config SmbConfig) string {
	var buf strings.Builder
	buf.WriteString("# Generated by CasaNova — do not edit manually.\n")
	buf.WriteString("[global]\n")
	buf.WriteString("   workgroup = " + sanitizeSmbField(config.Workgroup) + "\n")
	buf.WriteString("   server string = CasaNova\n")
	buf.WriteString("   security = user\n")
	buf.WriteString("   map to guest = Bad User\n")
	buf.WriteString("   log file = /var/log/samba/log.%m\n")
	buf.WriteString("   max log size = 1000\n")
	buf.WriteString("   logging = file\n\n")

	for _, share := range config.Shares {
		buf.WriteString("[" + sanitizeSmbField(share.Name) + "]\n")
		buf.WriteString("   path = " + sanitizeSmbField(share.Path) + "\n")
		if share.Comment != "" {
			buf.WriteString("   comment = " + sanitizeSmbField(share.Comment) + "\n")
		}
		if share.ReadOnly {
			buf.WriteString("   read only = yes\n")
		} else {
			buf.WriteString("   read only = no\n")
		}
		if share.GuestOk {
			buf.WriteString("   guest ok = yes\n")
		} else {
			buf.WriteString("   guest ok = no\n")
		}
		buf.WriteString("   browseable = yes\n")
		buf.WriteString("   create mask = 0664\n")
		buf.WriteString("   directory mask = 0775\n")
		if len(share.ValidUsers) > 0 {
			sanitizedUsers := make([]string, len(share.ValidUsers))
			for i, u := range share.ValidUsers {
				sanitizedUsers[i] = sanitizeSmbField(u)
			}
			buf.WriteString("   valid users = " + strings.Join(sanitizedUsers, " ") + "\n")
		}
		buf.WriteString("\n")
	}
	return buf.String()
}

func writeSmbConfAndReload(cfg SmbConfig) error {
	conf := generateSmbConf(cfg)
	// Wave 35-X: atomic write — torn smb.conf during reload would
	// crash smbd or expose unintended shares momentarily.
	if err := commonfile.WriteFileAtomic(smbConfPath, []byte(conf), 0o644); err != nil {
		return fmt.Errorf("failed to write smb.conf: %w", err)
	}
	// Only reload if smbd is running.
	if out, err := exec.Command("systemctl", "is-active", "smbd").Output(); err == nil {
		if strings.TrimSpace(string(out)) == "active" {
			exec.Command("systemctl", "reload", "smbd").Run()
		}
	}
	return nil
}

// ---- Validation ----

var shareNameRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9 _-]{0,63}$`)

func validateShareName(name string) bool {
	return shareNameRe.MatchString(name)
}

// smbBlockedPrefixes mirrors blockedSharePrefixes in samba.go. Wave 33:
// validateSharePath previously only enforced "absolute / no '..' /
// directory exists" — meaning an admin (or, before the RBAC gate
// added above, anyone) could publish /etc, /root, /var/log, etc. as
// a Samba share. Both samba.go and this file rewrite the live SMB
// configuration, so they need the same allow-list discipline.
var smbBlockedPrefixes = []string{
	"/etc", "/root", "/usr", "/var", "/sys", "/proc", "/dev", "/boot", "/bin", "/sbin", "/lib", "/lib64", "/run",
}

func validateSharePath(path string) bool {
	if !filepath.IsAbs(path) {
		return false
	}
	if strings.Contains(path, "..") {
		return false
	}
	clean := filepath.Clean(path)
	for _, prefix := range smbBlockedPrefixes {
		if clean == prefix || strings.HasPrefix(clean, prefix+"/") {
			return false
		}
	}
	// Use Lstat first so we don't blindly follow symlinks.
	info, err := os.Lstat(clean)
	if err != nil {
		return false
	}
	// If it's a symlink, resolve it and verify the target is under an
	// allowed directory (i.e. still absolute and not escaping to sensitive paths).
	if info.Mode()&os.ModeSymlink != 0 {
		resolved, err := filepath.EvalSymlinks(clean)
		if err != nil {
			return false
		}
		if !filepath.IsAbs(resolved) || strings.Contains(resolved, "..") {
			return false
		}
		// Re-apply the prefix block-list to the resolved target so a
		// symlink under /home cannot point at /etc/ssh.
		for _, prefix := range smbBlockedPrefixes {
			if resolved == prefix || strings.HasPrefix(resolved, prefix+"/") {
				return false
			}
		}
		// Re-stat the resolved path to confirm it's a directory.
		info, err = os.Stat(resolved)
		if err != nil {
			return false
		}
	}
	return info.IsDir()
}

// ---- Handlers ----

// GET /v1/sys/smb/status
func GetSmbStatus(ctx echo.Context) error {
	installed := true
	if _, err := exec.LookPath("smbd"); err != nil {
		installed = false
	}

	running := false
	if installed {
		if out, err := exec.Command("systemctl", "is-active", "smbd").Output(); err == nil {
			running = strings.TrimSpace(string(out)) == "active"
		}
	}

	cfg, _ := loadSmbConfig()

	return ctx.JSON(http.StatusOK, model.Result{
		Success: common_err.SUCCESS,
		Message: common_err.GetMsg(common_err.SUCCESS),
		Data: SmbStatusResponse{
			Installed: installed,
			Running:   running,
			Workgroup: cfg.Workgroup,
			Shares:    cfg.Shares,
		},
	})
}

// POST /v1/sys/smb/shares
func PostSmbShare(ctx echo.Context) error {
	// Wave 33: gate behind PermStorageWrite. This handler rewrites
	// /etc/samba/smb.conf and reloads smbd, so anyone reaching it
	// can publish arbitrary directories on the LAN. validateSharePath
	// only checks "absolute / no '..' / exists" — without an RBAC
	// gate a Guest could expose /etc/ssh, /var/log, /home/* to the
	// network. Bring this in line with samba.go's gates above and
	// every other write-side handler in this package.
	if err := requirePerm(ctx, rbac.PermStorageWrite); err != nil {
		return err
	}
	var share SmbShare
	if err := ctx.Bind(&share); err != nil {
		return ctx.JSON(http.StatusBadRequest, model.Result{
			Success: common_err.CLIENT_ERROR,
			Message: "invalid request body",
		})
	}

	share.Name = strings.TrimSpace(share.Name)
	share.Path = strings.TrimSpace(share.Path)

	if !validateShareName(share.Name) {
		return ctx.JSON(http.StatusBadRequest, model.Result{
			Success: common_err.CLIENT_ERROR,
			Message: "invalid share name: use letters, numbers, spaces, dashes, or underscores",
		})
	}
	if !validateSharePath(share.Path) {
		return ctx.JSON(http.StatusBadRequest, model.Result{
			Success: common_err.CLIENT_ERROR,
			Message: "invalid path: must be an existing absolute directory without '..'",
		})
	}

	smbMu.Lock()
	defer smbMu.Unlock()

	cfg, err := loadSmbConfig()
	if err != nil {
		return ctx.JSON(http.StatusInternalServerError, model.Result{
			Success: common_err.SERVICE_ERROR,
			Message: "failed to load config: " + err.Error(),
		})
	}

	// Check for duplicate name.
	nameLower := strings.ToLower(share.Name)
	for _, s := range cfg.Shares {
		if strings.ToLower(s.Name) == nameLower {
			return ctx.JSON(http.StatusConflict, model.Result{
				Success: common_err.SHARE_NAME_ALREADY_EXISTS,
				Message: common_err.GetMsg(common_err.SHARE_NAME_ALREADY_EXISTS),
			})
		}
	}

	cfg.Shares = append(cfg.Shares, share)

	if err := saveSmbConfig(cfg); err != nil {
		return ctx.JSON(http.StatusInternalServerError, model.Result{
			Success: common_err.SERVICE_ERROR,
			Message: "failed to save config: " + err.Error(),
		})
	}

	if err := writeSmbConfAndReload(cfg); err != nil {
		return ctx.JSON(http.StatusInternalServerError, model.Result{
			Success: common_err.SERVICE_ERROR,
			Message: err.Error(),
		})
	}

	return ctx.JSON(http.StatusOK, model.Result{
		Success: common_err.SUCCESS,
		Message: common_err.GetMsg(common_err.SUCCESS),
		Data:    share,
	})
}

// PUT /v1/sys/smb/shares/:name
func PutSmbShare(ctx echo.Context) error {
	if err := requirePerm(ctx, rbac.PermStorageWrite); err != nil {
		return err
	}
	name := ctx.Param("name")

	var share SmbShare
	if err := ctx.Bind(&share); err != nil {
		return ctx.JSON(http.StatusBadRequest, model.Result{
			Success: common_err.CLIENT_ERROR,
			Message: "invalid request body",
		})
	}

	share.Name = strings.TrimSpace(share.Name)
	share.Path = strings.TrimSpace(share.Path)

	if !validateShareName(share.Name) {
		return ctx.JSON(http.StatusBadRequest, model.Result{
			Success: common_err.CLIENT_ERROR,
			Message: "invalid share name",
		})
	}
	if !validateSharePath(share.Path) {
		return ctx.JSON(http.StatusBadRequest, model.Result{
			Success: common_err.CLIENT_ERROR,
			Message: "invalid path: must be an existing absolute directory without '..'",
		})
	}

	smbMu.Lock()
	defer smbMu.Unlock()

	cfg, err := loadSmbConfig()
	if err != nil {
		return ctx.JSON(http.StatusInternalServerError, model.Result{
			Success: common_err.SERVICE_ERROR,
			Message: "failed to load config: " + err.Error(),
		})
	}

	found := false
	nameLower := strings.ToLower(name)
	for i, s := range cfg.Shares {
		if strings.ToLower(s.Name) == nameLower {
			cfg.Shares[i] = share
			found = true
			break
		}
	}

	if !found {
		return ctx.JSON(http.StatusNotFound, model.Result{
			Success: common_err.Record_NOT_EXIST,
			Message: common_err.GetMsg(common_err.Record_NOT_EXIST),
		})
	}

	if err := saveSmbConfig(cfg); err != nil {
		return ctx.JSON(http.StatusInternalServerError, model.Result{
			Success: common_err.SERVICE_ERROR,
			Message: "failed to save config: " + err.Error(),
		})
	}

	if err := writeSmbConfAndReload(cfg); err != nil {
		return ctx.JSON(http.StatusInternalServerError, model.Result{
			Success: common_err.SERVICE_ERROR,
			Message: err.Error(),
		})
	}

	return ctx.JSON(http.StatusOK, model.Result{
		Success: common_err.SUCCESS,
		Message: common_err.GetMsg(common_err.SUCCESS),
		Data:    share,
	})
}

// DELETE /v1/sys/smb/shares/:name
func DeleteSmbShare(ctx echo.Context) error {
	if err := requirePerm(ctx, rbac.PermStorageWrite); err != nil {
		return err
	}
	name := ctx.Param("name")

	smbMu.Lock()
	defer smbMu.Unlock()

	cfg, err := loadSmbConfig()
	if err != nil {
		return ctx.JSON(http.StatusInternalServerError, model.Result{
			Success: common_err.SERVICE_ERROR,
			Message: "failed to load config: " + err.Error(),
		})
	}

	nameLower := strings.ToLower(name)
	found := false
	filtered := make([]SmbShare, 0, len(cfg.Shares))
	for _, s := range cfg.Shares {
		if strings.ToLower(s.Name) == nameLower {
			found = true
			continue
		}
		filtered = append(filtered, s)
	}

	if !found {
		return ctx.JSON(http.StatusNotFound, model.Result{
			Success: common_err.Record_NOT_EXIST,
			Message: common_err.GetMsg(common_err.Record_NOT_EXIST),
		})
	}

	cfg.Shares = filtered

	if err := saveSmbConfig(cfg); err != nil {
		return ctx.JSON(http.StatusInternalServerError, model.Result{
			Success: common_err.SERVICE_ERROR,
			Message: "failed to save config: " + err.Error(),
		})
	}

	if err := writeSmbConfAndReload(cfg); err != nil {
		return ctx.JSON(http.StatusInternalServerError, model.Result{
			Success: common_err.SERVICE_ERROR,
			Message: err.Error(),
		})
	}

	return ctx.JSON(http.StatusOK, model.Result{
		Success: common_err.SUCCESS,
		Message: common_err.GetMsg(common_err.SUCCESS),
		Data:    name,
	})
}

// POST /v1/sys/smb/toggle
func PostSmbToggle(ctx echo.Context) error {
	// Ungated peer of PostSmbShare/Put/Delete (PermStorageWrite).
	if err := requirePerm(ctx, rbac.PermStorageWrite); err != nil {
		return err
	}
	var body struct {
		Enabled bool `json:"enabled"`
	}
	if err := ctx.Bind(&body); err != nil {
		return ctx.JSON(http.StatusBadRequest, model.Result{
			Success: common_err.CLIENT_ERROR,
			Message: "invalid request body",
		})
	}

	if _, err := exec.LookPath("smbd"); err != nil {
		return ctx.JSON(http.StatusServiceUnavailable, model.Result{
			Success: common_err.SERVICE_ERROR,
			Message: "smbd is not installed",
		})
	}

	smbMu.Lock()
	defer smbMu.Unlock()

	cfg, _ := loadSmbConfig()
	cfg.Enabled = body.Enabled
	saveSmbConfig(cfg)

	if body.Enabled {
		// Regenerate smb.conf before starting.
		writeSmbConfAndReload(cfg)
		exec.Command("systemctl", "enable", "smbd").Run()
		if out, err := exec.Command("systemctl", "start", "smbd").CombinedOutput(); err != nil {
			return ctx.JSON(http.StatusInternalServerError, model.Result{
				Success: common_err.SERVICE_ERROR,
				Message: "failed to start smbd: " + strings.TrimSpace(string(out)),
			})
		}
	} else {
		exec.Command("systemctl", "stop", "smbd").Run()
		exec.Command("systemctl", "disable", "smbd").Run()
	}

	return ctx.JSON(http.StatusOK, model.Result{
		Success: common_err.SUCCESS,
		Message: common_err.GetMsg(common_err.SUCCESS),
		Data: map[string]bool{
			"enabled": body.Enabled,
		},
	})
}

// GET /v1/sys/smb/browse
func GetSmbBrowse(ctx echo.Context) error {
	// Gated: this EXECUTES avahi-browse: without a gate, any tokenless caller could trigger a network scan and read back the LAN's SMB hosts.
	if err := requirePerm(ctx, rbac.PermStorageRead); err != nil {
		return err
	}

	var entries []SmbBrowseEntry

	// Try avahi-browse first (mDNS discovery, no auth needed).
	if avahiPath, err := exec.LookPath("avahi-browse"); err == nil {
		out, err := exec.Command(avahiPath, "-rtp", "_smb._tcp").Output()
		if err == nil {
			seen := make(map[string]bool)
			for _, line := range strings.Split(string(out), "\n") {
				// avahi-browse -rtp output: +;eth0;IPv4;hostname;_smb._tcp;local;hostname.local;192.168.x.x;445
				fields := strings.Split(line, ";")
				if len(fields) < 8 || fields[0] != "=" {
					continue
				}
				host := fields[7] // IP address
				if host == "" || seen[host] {
					continue
				}
				seen[host] = true
				entry := SmbBrowseEntry{
					Host:   host,
					Shares: []string{},
				}
				// Try to list shares from this host.
				if shares := listRemoteShares(host); len(shares) > 0 {
					entry.Shares = shares
				}
				entries = append(entries, entry)
			}
		}
	}

	if entries == nil {
		entries = []SmbBrowseEntry{}
	}

	return ctx.JSON(http.StatusOK, model.Result{
		Success: common_err.SUCCESS,
		Message: common_err.GetMsg(common_err.SUCCESS),
		Data:    entries,
	})
}

// listRemoteShares tries to discover share names on a remote SMB host
// using smbclient with anonymous access.
func listRemoteShares(host string) []string {
	smbclientPath, err := exec.LookPath("smbclient")
	if err != nil {
		return nil
	}
	out, err := exec.Command(smbclientPath, "-L", host, "-N", "--option=client min protocol=SMB2").CombinedOutput()
	if err != nil {
		return nil
	}

	var shares []string
	for _, line := range strings.Split(string(out), "\n") {
		trimmed := strings.TrimSpace(line)
		// smbclient -L output lines for shares look like:
		//   ShareName       Disk      Some comment
		if strings.Contains(trimmed, "Disk") {
			parts := strings.Fields(trimmed)
			if len(parts) >= 2 && parts[1] == "Disk" {
				name := parts[0]
				// Skip IPC$ and hidden shares.
				if strings.HasSuffix(name, "$") {
					continue
				}
				shares = append(shares, name)
			}
		}
	}
	return shares
}
