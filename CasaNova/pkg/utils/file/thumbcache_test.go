func writeJPEG(t *testing.T, path string, w, h int, c color.RGBA) {
	t.Helper()
	img := image.NewRGBA(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			img.Set(x, y, c)
		}
	}
	var buf bytes.Buffer
	if err := jpeg.Encode(&buf, img, &jpeg.Options{Quality: 85}); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
}

// THE FAILURE MODE THAT MATTERS MOST.
//
// A cache keyed on the path alone serves the OLD thumbnail forever after the
// file is replaced. That turns a slow feature into a wrong one, which is worse:
// slow is visible, wrong is not. The key mixes in the source's mtime and size,
// so a replaced file misses by construction.
func TestAReplacedFileDoesNotServeTheOldThumbnail(t *testing.T) {
	SetThumbnailCacheDirForTest(t.TempDir())
	src := filepath.Join(t.TempDir(), "pic.jpg")

	writeJPEG(t, src, 200, 200, color.RGBA{255, 0, 0, 255})
	red, err := GetImage(src, 100, 0)
	if err != nil {
		t.Fatal(err)
	}

	// Replace the content. Force a distinct mtime so the test does not depend
	// on filesystem timestamp granularity.
	time.Sleep(10 * time.Millisecond)
	writeJPEG(t, src, 200, 200, color.RGBA{0, 0, 255, 255})
	if err := os.Chtimes(src, time.Now(), time.Now().Add(time.Second)); err != nil {
		t.Fatal(err)
	}

	blue, err := GetImage(src, 100, 0)
	if err != nil {
		t.Fatal(err)
	}
	if bytes.Equal(red, blue) {
		t.Fatal("the cache served the OLD thumbnail for a file whose contents " +
			"changed — a stale image is worse than a slow one, because nothing " +
			"about it looks wrong")
	}
}

// The same source at a different size must not collide.
func TestDifferentSizesDoNotShareAnEntry(t *testing.T) {
	SetThumbnailCacheDirForTest(t.TempDir())
	src := filepath.Join(t.TempDir(), "pic.jpg")
	writeJPEG(t, src, 400, 400, color.RGBA{10, 200, 10, 255})

	small, err := GetImage(src, 50, 0)
	if err != nil {
		t.Fatal(err)
	}
	large, err := GetImage(src, 300, 0)
	if err != nil {
		t.Fatal(err)
	}
	if bytes.Equal(small, large) {
		t.Fatal("two different requested widths returned identical bytes: the key " +
			"does not include the size, so one size is serving the other's image")
	}
}

// A COLD KEY MUST NOT STAMPEDE. A gallery opens and asks for the same image
// from many goroutines at once; without singleflight every one of them pays the
// 650 ms full decode, so the cache is absent exactly when it is needed most.
func TestConcurrentRequestsGenerateOnlyOnce(t *testing.T) {
	SetThumbnailCacheDirForTest(t.TempDir())
	src := filepath.Join(t.TempDir(), "pic.jpg")
	writeJPEG(t, src, 300, 300, color.RGBA{1, 2, 3, 255})

	var generated atomic.Int32
	gen := func() ([]byte, error) {
		generated.Add(1)
		time.Sleep(20 * time.Millisecond) // make the window real
		return []byte("thumb-bytes"), nil
	}

	var wg sync.WaitGroup
	for i := 0; i < 20; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			if _, err := CachedImage(src, 100, 0, gen); err != nil {
				t.Error(err)
			}
		}()
	}
	wg.Wait()

	if n := generated.Load(); n != 1 {
		t.Fatalf("20 concurrent requests for one cold thumbnail ran the generator "+
			"%d times, not once — that is 650 ms of decode per caller on a gallery "+
			"load", n)
	}
}

// THE CACHE MUST NEVER BE ABLE TO BREAK THE FEATURE. An unwritable directory is
// an optimisation that is unavailable, not a failed request.
func TestAnUnusableCacheStillServesThumbnails(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "ro", "thumbs")
	if err := os.MkdirAll(filepath.Dir(dir), 0o500); err != nil {
		t.Fatal(err)
	}
	SetThumbnailCacheDirForTest(dir)

	src := filepath.Join(t.TempDir(), "pic.jpg")
	writeJPEG(t, src, 120, 120, color.RGBA{9, 9, 9, 255})

	got, err := CachedImage(src, 100, 0, func() ([]byte, error) { return []byte("generated"), nil })
	if err != nil {
		t.Fatalf("a cache that cannot be written failed the request: %v", err)
	}
	if string(got) != "generated" {
		t.Fatalf("got %q, want the generated bytes", got)
	}
}

// A partially written entry must never be readable as a thumbnail.
func TestEntriesAreWrittenAtomically(t *testing.T) {
	dir := t.TempDir()
	SetThumbnailCacheDirForTest(dir)
	src := filepath.Join(t.TempDir(), "pic.jpg")
	writeJPEG(t, src, 150, 150, color.RGBA{7, 7, 7, 255})

	if _, err := GetImage(src, 100, 0); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		if len(e.Name()) >= 5 && e.Name()[:5] == ".tmp-" {
			t.Fatalf("a temporary file %q survived: a reader could pick up a "+
				"partial JPEG", e.Name())
		}
	}
	if len(entries) != 1 {
		t.Fatalf("expected exactly one cache entry, found %d", len(entries))
	}
}
