// useComposeYaml — serialize an AppEntry (with edited services) into
// a valid docker-compose.yml string.
//
// Hand-written serializer rather than pulling in a YAML library — the
// shape is small, predictable, and fully under our control. The
// generator:
//   - Indents with 2 spaces
//   - Quotes string values that might be misread as YAML (digits,
//     booleans, empty strings)
//   - Expands PortProtocol='both' into two Docker port entries
//   - Omits empty sections so the output stays tidy
//
// Used by the "View compose.yml" dialog in the app detail view.

import type { AppEntry, ServiceEntry, PortMapping } from '@/types/containers'

function needsQuote(v: string): boolean {
  if (v === '') return true
  if (/^(true|false|yes|no|null|~)$/i.test(v)) return true
  if (/^-?\d/.test(v)) return true
  if (/[:#"'\[\]{}&*!|>%@`]/.test(v)) return true
  return false
}

function quote(v: string): string {
  const escaped = v.replace(/"/g, '\\"')
  return `"${escaped}"`
}

function yamlString(v: string): string {
  return needsQuote(v) ? quote(v) : v
}

function portsForYaml(ports: PortMapping[]): string[] {
  const out: string[] = []
  for (const p of ports) {
    if (p.protocol === 'both') {
      out.push(`"${p.host}:${p.container}/tcp"`)
      out.push(`"${p.host}:${p.container}/udp"`)
    } else {
      out.push(`"${p.host}:${p.container}/${p.protocol}"`)
    }
  }
  return out
}

function serializeService(svc: ServiceEntry, serviceName: string): string[] {
  const lines: string[] = []
  lines.push(`  ${serviceName}:`)
  lines.push(`    image: ${yamlString(svc.dockerImage + ':' + svc.imageTag)}`)
  lines.push(`    container_name: ${serviceName}`)
  lines.push(`    restart: ${svc.restartPolicy}`)

  if (svc.command) {
    lines.push(`    command: ${yamlString(svc.command)}`)
  }
  if (svc.privileged) {
    lines.push(`    privileged: true`)
  }

  if (svc.ports.length > 0) {
    lines.push(`    ports:`)
    for (const p of portsForYaml(svc.ports)) {
      lines.push(`      - ${p}`)
    }
  }

  if (svc.volumes.length > 0) {
    lines.push(`    volumes:`)
    for (const v of svc.volumes) {
      const suffix = v.readOnly ? ':ro' : ''
      lines.push(`      - ${yamlString(v.hostPath + ':' + v.containerPath + suffix)}`)
    }
  }

  if (svc.devices.length > 0) {
    lines.push(`    devices:`)
    for (const d of svc.devices) {
      lines.push(`      - ${yamlString(d.hostPath + ':' + d.containerPath)}`)
    }
  }

  if (svc.env.length > 0) {
    lines.push(`    environment:`)
    for (const e of svc.env) {
      lines.push(`      - ${e.key}=${yamlString(e.value)}`)
    }
  }

  if (svc.networks.length > 0) {
    lines.push(`    networks:`)
    for (const n of svc.networks) {
      lines.push(`      - ${n}`)
    }
  }

  // Deploy block for resource limits — the 3.x compose syntax.
  if (svc.cpuLimitCores || svc.memoryLimitMB) {
    lines.push(`    deploy:`)
    lines.push(`      resources:`)
    lines.push(`        limits:`)
    if (svc.cpuLimitCores) {
      lines.push(`          cpus: "${svc.cpuLimitCores}"`)
    }
    if (svc.memoryLimitMB) {
      lines.push(`          memory: ${svc.memoryLimitMB}M`)
    }
  }

  return lines
}

/**
 * Build the compose file for an app. Uses the currently-edited service
 * list (callers pass the live editableServices array rather than the
 * fixture) so the YAML reflects unsaved changes — users see what they
 * would ship before they click Save.
 */
export function buildComposeYaml(app: AppEntry, services: ServiceEntry[]): string {
  const lines: string[] = []
  lines.push(`# docker-compose.yml for ${app.title}`)
  lines.push(`# Generated by CasaNova`)
  lines.push(`version: "3.8"`)
  lines.push(``)
  lines.push(`services:`)
  for (const svc of services) {
    lines.push(...serializeService(svc, svc.id))
  }

  // Collect unique network names so we can declare them at the bottom.
  // Docker compose accepts external networks without declaration, but
  // listing them keeps the file self-describing.
  const networks = new Set<string>()
  for (const svc of services) {
    for (const n of svc.networks) networks.add(n)
  }
  if (networks.size > 0) {
    lines.push(``)
    lines.push(`networks:`)
    for (const n of networks) {
      lines.push(`  ${n}:`)
      // `bridge` is a Docker built-in, don't redeclare it as managed.
      if (n === 'bridge' || n === 'host') {
        lines.push(`    external: true`)
      } else {
        lines.push(`    driver: bridge`)
      }
    }
  }

  return lines.join('\n') + '\n'
}

/**
 * Trigger a browser download for the given YAML string.
 */
export function downloadYaml(filename: string, contents: string): void {
  const blob = new Blob([contents], { type: 'text/yaml;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  // Small timeout before revoking so the browser has started the
  // download before the URL disappears.
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}
