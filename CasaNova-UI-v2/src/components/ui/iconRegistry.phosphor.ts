// Phosphor half of the icon registry, split into its own module purely so the
// bundler can put it behind a dynamic import (see ./iconRegistry). It has to be
// a separate file: lazily pulling the package namespace instead
// (`import('@phosphor-icons/vue')`) defeats tree-shaking — rollup cannot tell
// which of the 4.5k exports we touch and ships every one of them (5.7 MB
// measured). Static named imports behind one dynamic module boundary keep the
// chunk down to the ~136 components mapped below.
//
// Keys are Lucide names, because that is what AppIcon's `name` prop speaks;
// this map is the translation. Every key in `lucideIcons` must appear here or
// AppIcon silently falls back to a glyph from the other family — and a key that
// resolves to nothing renders NOTHING at all, with no error.
//
// That invariant used to be honour-system only: a missing key is not a type
// error, it just paints an empty box in production. ./iconRegistry.spec.ts now
// enforces it — it diffs the two key sets and re-checks every icon name the app
// actually uses. Run `npm test` after touching either map.

